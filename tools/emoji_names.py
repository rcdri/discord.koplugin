#!/usr/bin/env python3
"""Generates discord_emoji_names.lua: the name of every emoji, so the chat can
show ":pink_heart:" instead of a generic "[emoji]" (e-reader fonts can't draw them).

    npm pack emojibase-data && tar -xzf emojibase-data-*.tgz
    python3 tools/emoji_names.py package

Names are the joypixels shortcodes from emojibase-data, which match the
names Discord shows (slight_smile, upside_down, thumbsup, flag_pt...). The
few newest emoji without one fall back to the GitHub shortcode, then to the
Unicode name.

Keys are the emoji without variation selectors (FE0E/FE0F) or skin tones,
since the plugin strips those before looking names up. Single characters
below U+10000 are left out: the plugin keeps those as they are.
"""

import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "discord_emoji_names.lua")
SKIN_TONES = {chr(c) for c in range(0x1F3FB, 0x1F400)}


def first(codes):
    if isinstance(codes, list):
        return codes[0] if codes else None
    return codes


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    pkg = sys.argv[1]
    data = json.load(open(os.path.join(pkg, "en", "data.json"), encoding="utf-8"))
    joypixels = json.load(open(os.path.join(pkg, "en", "shortcodes", "joypixels.json"), encoding="utf-8"))
    github = json.load(open(os.path.join(pkg, "en", "shortcodes", "github.json"), encoding="utf-8"))
    version = json.load(open(os.path.join(pkg, "package.json"), encoding="utf-8"))["version"]

    names = {}
    for e in data:
        if e.get("group") == 2:  # components: skin tones, hair styles
            continue
        key = "".join(c for c in e["emoji"] if c not in "︎️" and c not in SKIN_TONES)
        if len(key) == 1 and ord(key) < 0x10000:
            continue
        name = first(joypixels.get(e["hexcode"])) or first(github.get(e["hexcode"]))
        if not name:
            name = re.sub(r"[^a-z0-9]+", "_", e["label"].lower()).strip("_")
        names.setdefault(key, name)

    def lua_string(s):
        return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

    lines = [
        "-- Emoji names (as Discord shows them), keyed by emoji without variation",
        "-- selectors or skin tones. Generated by tools/emoji_names.py from",
        "-- emojibase-data %s (joypixels shortcodes); do not edit by hand." % version,
        "return {",
    ]
    for key in sorted(names, key=lambda k: [ord(c) for c in k]):
        lines.append("    [%s] = %s," % (lua_string(key), lua_string(names[key])))
    lines.append("}")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("%d names written to %s" % (len(names), os.path.relpath(OUT, ROOT)))


if __name__ == "__main__":
    main()
